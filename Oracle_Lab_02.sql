CREATE TABLE PRODUCTOS (
    ID_FAB      VARCHAR2(10) NOT NULL,
    ID_PRODUCTO VARCHAR2(10) NOT NULL,
    DESCRIPCION VARCHAR2(100) NOT NULL,
    PRECIO      NUMBER(10,2) NOT NULL,
    EXISTENCIA  NUMBER NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (ID_FAB, ID_PRODUCTO)
);

CREATE TABLE PEDIDOS (
    NUM_PEDIDO   NUMBER PRIMARY KEY,
    FECHA_PEDIDO DATE NOT NULL,
    CLIE         NUMBER NOT NULL,          
    REP          NUMBER NOT NULL,          
    FAB          VARCHAR2(10) NOT NULL,    
    PRODUCTO     VARCHAR2(10) NOT NULL,    
    CANT         NUMBER NOT NULL,
    IMPORTE      NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_ped_clie  FOREIGN KEY (CLIE) REFERENCES CLIENTES(NUM_CLIE),
    CONSTRAINT fk_ped_rep   FOREIGN KEY (REP)  REFERENCES REPVENTAS(NUM_EMPL),
    CONSTRAINT fk_ped_prod  FOREIGN KEY (FAB, PRODUCTO) REFERENCES PRODUCTOS(ID_FAB, ID_PRODUCTO)
);

