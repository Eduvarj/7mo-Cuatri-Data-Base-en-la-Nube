CREATE TABLE OFICINAS (
    OFICINA   NUMBER PRIMARY KEY,
    CIUDAD    VARCHAR2(50) NOT NULL,
    REGION    VARCHAR2(50) NOT NULL,
    DIR       NUMBER,          
    OBJETIVO  NUMBER(10,2) NOT NULL,
    VENTAS    NUMBER(10,2) NOT NULL
);

CREATE TABLE REPVENTAS (
    NUM_EMPL    NUMBER PRIMARY KEY,
    NOMBRE      VARCHAR2(50) NOT NULL,
    EDAD        NUMBER NOT NULL,
    OFICINA_REP NUMBER NOT NULL,          
    TITULO      VARCHAR2(50) NOT NULL,
    CONTRATO    DATE NOT NULL,
    DIRECTOR    NUMBER,          
    CUOTA       NUMBER(10,2) NOT NULL,
    VENTAS      NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_rep_oficina FOREIGN KEY (OFICINA_REP) REFERENCES OFICINAS(OFICINA),
    CONSTRAINT fk_rep_director FOREIGN KEY (DIRECTOR) REFERENCES REPVENTAS(NUM_EMPL)
);

CREATE TABLE CLIENTES (
    NUM_CLIE    NUMBER PRIMARY KEY,
    EMPRESA     VARCHAR2(50) NOT NULL,
    REP_CLIENTE NUMBER NOT NULL,          
    LIM_CREDITO NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_clie_rep FOREIGN KEY (REP_CLIENTE) REFERENCES REPVENTAS(NUM_EMPL)
);
